export function getNewspaper(id: string | null | undefined): Newspaper | undefined {
  return newspapers.find((n) => n.id === id);
}

export function getEdition(editionId: string): { paper: Newspaper; edition: Edition } | undefined {
  for (const paper of newspapers) {
    const edition = paper.editions.find((e) => e.id === editionId);
    if (edition) return { paper, edition };
  }
  return undefined;
}

export function getGroup(paper: Newspaper, groupId: string) {
  return paper.groups.find((g) => g.id === groupId);
}
