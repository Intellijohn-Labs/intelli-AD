import type { Quote } from "@/lib/pricing";
import type { BookingState } from "@/lib/booking-store";
import { displayWidth } from "@/lib/display";
import { applySpacing } from "@/lib/paragraphs";
import { getNewspaper } from "@/data/newspapers";
import { createClient, supabaseConfigured } from "./client";

export type BookingStatus = "pending_payment" | "confirmed";

/** A row of the `bookings` table (column names as in the database). */
export interface BookingRow {
  booking_ref: string;
  ad_type: string;
  category: string | null;
  publication: string;
  editions: Record<string, string[]>;
  release_date: string | null;
  ad_text: string | null;
  artwork_url: string | null;
  dimensions: { width: number | null; height: number | null; lines: number };
  enhancements: Record<string, unknown>;
  pricing: Record<string, number>;
  customer_details: Record<string, unknown>;
  status: BookingStatus;
}

export interface CustomerDetails {
  name: string;
  mobile: string;
  email: string;
  address: string;
  company?: string;
  gstin?: string;
}

/** INT-2026-123456 */
export const newBookingRef = () => `INT-${new Date().getFullYear()}-${Math.floor(100000 + Math.random() * 900000)}`;

/** Maps the booking wizard state and quote to a `bookings` row. */
export function buildBookingRow(state: BookingState, quote: Quote, customer: CustomerDetails, ref: string, status: BookingStatus): BookingRow {
  const paperIds = Object.keys(state.selection).filter((k) => state.selection[k].length);
  const isText = state.adType === "classified-text";
  const colW = getNewspaper(paperIds[0])?.rates.colWidthCm ?? 4;
  return {
    booking_ref: ref,
    ad_type: state.adType,
    category: state.categoryId,
    publication: paperIds.map((id) => getNewspaper(id)?.name ?? id).join(", "),
    editions: Object.fromEntries(paperIds.map((id) => [id, state.selection[id]])),
    release_date: state.releaseDate,
    ad_text: state.text.trim() ? (isText ? applySpacing(state.text, state.paragraphSpacing).trim() : state.text.trim()) : null,
    artwork_url: state.artwork?.url ?? null,
    dimensions: isText
      ? { width: null, height: null, lines: quote.metrics.lines }
      : { width: displayWidth(state.display, colW), height: state.display.heightCm, lines: quote.metrics.lines },
    enhancements: { ...state.enhancements, colorMode: state.display.colorMode },
    pricing: { baseRate: quote.totals.base, gst: quote.totals.gst, total: quote.totals.total, extra: quote.totals.extra, discount: quote.totals.discount },
    customer_details: { ...customer },
    status,
  };
}

/**
 * Inserts one booking. The reference is generated by the caller beforehand and sent in the payload, and there is
 * deliberately no `.select()` after `.insert()`: Row Level Security gives the public key INSERT only, so reading the
 * row back would be blocked. On success the same reference is handed back for the receipt.
 */
export async function saveBooking(row: BookingRow): Promise<{ ok: boolean; ref?: string; skipped?: boolean; error?: string }> {
  const supabase = createClient();
  if (!supabase) return { ok: false, skipped: true, error: "Database is not configured." };
  const { error } = await supabase.from("bookings").insert(row);
  return error ? { ok: false, error: error.message } : { ok: true, ref: row.booking_ref };
}

