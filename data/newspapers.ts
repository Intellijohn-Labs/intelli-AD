import type { AdType, CutoffRule, Edition, Newspaper } from "@/lib/types";

const slug = (s: string) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

function editions(paperId: string, rows: [name: string, groupId: string, weight: number][]): Edition[] {
  return rows.map(([name, groupId, weight]) => ({
    id: `${paperId}--${slug(name)}`,
    name,
    groupId,
    weight,
  }));
}

function cutoffs(
  text: [number, string],
  classifiedDisplay: [number, string],
  display: [number, string],
): Record<AdType, CutoffRule> {
  const rule = ([daysBefore, time]: [number, string]): CutoffRule => ({ daysBefore, time });
  return {
    "classified-text": rule(text),
    "classified-display": rule(classifiedDisplay),
    "commercial-display": rule(display),
  };
}

